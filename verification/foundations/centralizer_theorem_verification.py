def compute_centralizer(subgroup_indices, elements):
    """Compute the centralizer C_O(H) = {g ∈ O : gh = hg for all h ∈ H}.

    Returns the set of indices of elements that commute with all elements
    of the given subgroup.
    """
    centralizer = []
    for i, g in enumerate(elements):
        commutes_with_all = True
        for j in subgroup_indices:
            h = elements[j]
            gh = g @ h
            hg = h @ g
            if not matrices_equal(gh, hg):
                commutes_with_all = False
                break
        if commutes_with_all:
            centralizer.append(i)
    return set(centralizer)


