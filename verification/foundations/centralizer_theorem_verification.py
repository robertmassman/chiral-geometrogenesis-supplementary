def check_product_embeddings(elements, z3_subgroups):
    """Check whether Z₃ × Z₂, Z₃ × Z₃, or Z₆ can embed in O."""
    results = {}

    n = len(elements)
    orders = [matrix_order(M) for M in elements]

    # Z₃ × Z₃ (order 9): requires two commuting order-3 elements
    # generating distinct Z₃ subgroups
    z3z3_found = False
    for i in range(n):
        if orders[i] != 3:
            continue
        for j in range(i+1, n):
            if orders[j] != 3:
                continue
            # Check if they commute
            if not matrices_equal(elements[i] @ elements[j], elements[j] @ elements[i]):
                continue
            # Check if they generate distinct Z₃ subgroups
            i2 = find_index(elements[i] @ elements[i], elements)
            if j == i2:
                continue  # Same Z₃ subgroup
            z3z3_found = True
            break
        if z3z3_found:
            break
    results["Z3_x_Z3_embeds"] = z3z3_found
    results["Z3_x_Z3_order_divides_24"] = (24 % 9 == 0)

    # Z₆ (order 6): requires an element of order 6
    has_order_6 = any(o == 6 for o in orders)
    results["Z6_embeds"] = has_order_6
    results["order_6_elements_exist"] = has_order_6

    # Z₃ × Z₂ ≅ Z₆: same as above (Z₃ × Z₂ is cyclic when gcd(3,2)=1)
    results["Z3_x_Z2_iso_Z6"] = True
    results["Z3_x_Z2_embeds"] = has_order_6

    # Maximum order of elements in O
    results["max_element_order"] = max(orders)
    results["order_distribution"] = {str(k): orders.count(k) for k in sorted(set(orders))}

    return results


