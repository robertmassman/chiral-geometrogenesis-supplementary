def find_z3_subgroups(elements):
    """Find all Z₃ subgroups of O.

    A Z₃ subgroup is generated by an element of order 3.
    Since each Z₃ has two generators (g and g²), we avoid double-counting.
    """
    order_3_elements = []
    for i, M in enumerate(elements):
        if matrix_order(M) == 3:
            order_3_elements.append((i, M))

    # Group into Z₃ subgroups: {I, g, g²}
    subgroups = []
    used = set()
    identity = np.eye(3)

    for i, g in order_3_elements:
        if i in used:
            continue
        g2 = g @ g
        j = find_index(g2, elements)
        subgroup = {0, i, j}  # 0 = identity
        used.add(i)
        used.add(j)
        subgroups.append(subgroup)

    return subgroups, order_3_elements


