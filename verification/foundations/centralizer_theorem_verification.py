def find_all_abelian_subgroups(elements):
    """Find all abelian subgroups of O, focusing on those containing Z₃."""
    n = len(elements)

    # Build multiplication table using vectorized comparison
    # Pre-flatten elements for faster comparison
    flat_elements = np.array([M.flatten() for M in elements])  # shape (n, 9)

    mult_table = np.zeros((n, n), dtype=int)
    for i in range(n):
        for j in range(n):
            product = (elements[i] @ elements[j]).flatten()
            diffs = np.linalg.norm(flat_elements - product[np.newaxis, :], axis=1)
            mult_table[i, j] = np.argmin(diffs)

    # Generate cyclic subgroups
    abelian_subgroups = set()
    for i in range(n):
        subgroup = {0}
        current = i
        for _ in range(30):
            subgroup.add(current)
            current = mult_table[current, i]
            if current == 0:
                break
        abelian_subgroups.add(frozenset(subgroup))

    # Try combining pairs of commuting elements
    for i in range(n):
        for j in range(i+1, n):
            if mult_table[i, j] != mult_table[j, i]:
                continue
            # Generate the subgroup <i, j>
            subgroup = {0, i, j}
            for _ in range(10):  # bounded iterations
                new_elements = set()
                for a in subgroup:
                    for b in subgroup:
                        p = mult_table[a, b]
                        if p not in subgroup:
                            new_elements.add(p)
                if not new_elements:
                    break
                subgroup.update(new_elements)
            # Check if abelian
            is_abelian = all(
                mult_table[a, b] == mult_table[b, a]
                for a in subgroup for b in subgroup
            )
            if is_abelian:
                abelian_subgroups.add(frozenset(subgroup))

    return abelian_subgroups, mult_table


